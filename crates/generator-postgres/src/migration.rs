use schema::{diagnostics::Report, root::Schema, uid::RenameMap};

use crate::Pg;

#[derive(Default, Clone, Debug, PartialEq, Eq)]
pub enum NonDestructive {
	#[default]
	Off,
	Keep(String),
	Fail,
}

#[derive(Default, Clone)]
pub struct UserSql {
	pub before_up: String,
	pub after_up: String,
	pub before_down: String,
	pub after_down: String,
}

fn decorate_automatically_generated(text: &mut String, has_before: bool, has_after: bool) {
	if !has_before && !has_after {
		text.insert_str(0, "-- THIS FILE IS AUTOMATICALLY GENERATED, DO NOT EDIT\n")
	} else if !has_after {
		text.insert_str(
			0,
			"-- THE REST OF THE FILE IS AUTOMATICALLY GENERATED, DO NOT EDIT\n",
		)
	} else {
		text.insert_str(0, "-- BEGIN OF AUTOMATICALLY GENERATED, DO NOT EDIT!\n");
		text.push_str("\n-- END OF AUTOMATICALLY GENERATED");
	}
}
fn decorate_before(text: &mut String, before: &str) {
	if before.is_empty() {
		return;
	}
	text.insert_str(0, "\n-- END OF USER ADDED\n\n");
	text.insert_str(0, before);
	text.insert_str(
		0,
		"-- BEGIN OF USER ADDED, DO NOT EDIT, UPDATE db.update INSTEAD!\n",
	);
}
fn decorate_after(text: &mut String, after: &str) {
	if after.is_empty() {
		return;
	}
	text.push_str("\n\n-- BEGIN OF USER ADDED, DO NOT EDIT, UPDATE db.update INSTEAD\n");
	text.push_str(after);
	text.push_str("\n-- END OF USER ADDED");
}

pub fn migration_sql(
	user: &UserSql,
	non_destructive: &NonDestructive,
	old_schema: &Schema,
	new_schema: &Schema,
	rn: &RenameMap,
	report_old: &mut Report,
	report_new: &mut Report,
) -> (String, String) {
	let mut up = String::new();
	let mut down = String::new();
	Pg(new_schema).diff_with(
		&Pg(old_schema),
		&mut up,
		&mut rn.clone(),
		report_old,
		report_new,
		non_destructive,
	);
	Pg(old_schema).diff(
		&Pg(new_schema),
		&mut down,
		&mut rn.clone(),
		report_new,
		report_old,
	);

	decorate_automatically_generated(
		&mut up,
		!user.before_up.is_empty(),
		!user.after_up.is_empty(),
	);
	decorate_automatically_generated(
		&mut down,
		!user.before_down.is_empty(),
		!user.after_down.is_empty(),
	);
	decorate_before(&mut up, &user.before_up);
	decorate_before(&mut down, &user.before_down);
	decorate_after(&mut up, &user.after_up);
	decorate_after(&mut down, &user.after_down);
	(up, down)
}

#[cfg(test)]
mod tests {
	use schema::{
		diagnostics::Report,
		parser::{SchemaVersion, parse},
		process::NamingConvention,
		root::{Schema, SchemaProcessOptions},
		uid::RenameMap,
	};

	use super::{NonDestructive, UserSql, migration_sql};

	const OLD: &str = r#"
		scalar id = sql"INTEGER";
		enum Kind { a; b; };
		table User {
			id @primary_key;
			name: sql"TEXT" @default("x");
			kind: Kind;
			@index(name);
		};
		table Post {
			id @primary_key;
			author: id ~ User(id);
		};
	"#;
	const NEW: &str = r#"
		scalar id = sql"INTEGER";
		table Post {
			id @primary_key;
		};
	"#;

	fn schema(src: &str, rn: &mut RenameMap) -> Schema {
		parse(
			src,
			SchemaVersion::Current,
			&SchemaProcessOptions {
				generator_supports_domain: true,
				naming_convention: NamingConvention::Postgres,
			},
			rn,
			&mut Report::new(),
		)
		.expect("valid schema")
	}

	fn up(mode: NonDestructive) -> (String, Vec<String>) {
		let mut rn = RenameMap::new();
		let old = schema(OLD, &mut rn);
		let new = schema(NEW, &mut rn);
		let mut report_old = Report::new();
		let (up, _) = migration_sql(
			&UserSql::default(),
			&mode,
			&old,
			&new,
			&rn,
			&mut report_old,
			&mut Report::new(),
		);
		let errors = report_old.parts.into_iter().map(|p| p.msg).collect();
		(up, errors)
	}

	#[test]
	fn keep() {
		let (sql, errors) = up(NonDestructive::Keep("7".to_owned()));
		assert!(errors.is_empty());
		assert_eq!(
			sql,
			"-- THIS FILE IS AUTOMATICALLY GENERATED, DO NOT EDIT\n\
			ALTER TABLE posts DROP CONSTRAINT posts_author_fk;\n\
			ALTER TABLE posts RENAME COLUMN author TO obsolete_7_author;\n\
			ALTER TABLE posts\n\
			\tALTER COLUMN obsolete_7_author DROP NOT NULL\n\
			,\tALTER COLUMN obsolete_7_author SET DATA TYPE INTEGER USING obsolete_7_author::INTEGER\n\
			;\n\
			DROP INDEX users_name_idx;\n\
			ALTER TABLE users\n\
			\tDROP CONSTRAINT users_id_pkey\n\
			,\tALTER COLUMN id SET DATA TYPE INTEGER USING id::INTEGER\n\
			,\tALTER COLUMN name DROP DEFAULT\n\
			,\tALTER COLUMN kind SET DATA TYPE TEXT USING kind::TEXT\n\
			;\n\
			ALTER TABLE users RENAME TO obsolete_7_users;\n\
			DROP TYPE \"Kind\";\n"
		);
	}

	#[test]
	fn fail() {
		let (_, errors) = up(NonDestructive::Fail);
		assert_eq!(
			errors,
			vec![
				"column `author` would be dropped, but data destruction is not allowed",
				"table `users` would be dropped, but data destruction is not allowed",
			]
		);
	}
}
